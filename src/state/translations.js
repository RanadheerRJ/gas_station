/**
 * The whole interface, in three languages.
 *
 * A fuel station in Telangana is staffed by people who read Telugu or Hindi
 * far more comfortably than English, while the owner's accountant usually
 * wants English. So the language is a per-device preference rather than an
 * account setting, and it covers every fixed string the app draws.
 *
 * What is NOT translated, deliberately:
 *
 *   · Anything a user typed — staff names, customer names, station names,
 *     notes, expense labels, invoice numbers. Rewriting a person's name into
 *     another script is both wrong and unhelpful.
 *   · Fuel product names, which are printed in English on the dispenser.
 *   · CSV and PDF column headings; see the note in src/lib/export.js.
 *
 * Every key below exists in all three dictionaries. `scripts/../language
 * coverage` is asserted by a unit test, so a key added to English without a
 * Telugu or Hindi counterpart fails the build rather than silently falling
 * back on screen.
 */

